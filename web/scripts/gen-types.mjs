// Generate src/types/generated.ts from ../schemas/*.schema.json (exported from the pydantic contracts).
// All schemas are merged into one document so shared $defs (Persona, WinProbability, …) are emitted once.
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const schemaDir = resolve(here, "../../schemas");
const outFile = resolve(here, "../src/types/generated.ts");

// Pydantic puts a `title` on every property; json-schema-to-typescript would turn each into a named
// alias (Headline1, MatchId3, �). Keep titles only on the model definitions themselves.
function stripTitles(node, keep) {
  if (Array.isArray(node)) return node.forEach((n) => stripTitles(n, false));
  if (node && typeof node === "object") {
    if (!keep) delete node.title;
    for (const [k, v] of Object.entries(node)) {
      if (k === "$defs") Object.values(v).forEach((d) => stripTitles(d, true));
      else stripTitles(v, false);
    }
  }
}

const defs = {};
for (const file of readdirSync(schemaDir).filter((f) => f.endsWith(".schema.json")).sort()) {
  const schema = JSON.parse(readFileSync(join(schemaDir, file), "utf8"));
  stripTitles(schema, true);
  const { $defs = {}, ...top } = schema;
  Object.assign(defs, $defs);
  defs[top.title] = top;
}

const root = {
  title: "FulcrumContracts",
  type: "object",
  additionalProperties: false,
  properties: Object.fromEntries(Object.keys(defs).map((k) => [k, { $ref: `#/$defs/${k}` }])),
  $defs: defs,
};

const ts = await compile(root, "FulcrumContracts", {
  bannerComment:
    "/* eslint-disable */\n/**\n * GENERATED by scripts/gen-types.mjs from ../schemas — do not edit by hand.\n * Run `npm run types` after `make schemas`.\n */",
  additionalProperties: false,
  unreachableDefinitions: true,
  style: { singleQuote: false },
});
mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, ts.replace(/\r\n/g, "\n"));
console.log(`wrote ${outFile} (${Object.keys(defs).length} types)`);
